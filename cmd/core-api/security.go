package main

import (
	"errors"
	"fmt"
	"os"
	"strings"

	"safe-zone/internal/auth"
	"safe-zone/internal/config"
	"safe-zone/internal/logjson"
)

const (
	generatedSessionSecretBytes = 32
	generatedAdminPasswordBytes = 16
	generatedAdminAPIKeyBytes   = 24
	minAdminPasswordLength      = 12
	maxAdminPasswordBytes       = 72 // bcrypt hashes at most 72 input bytes
	minAdminAPIKeyLength        = 24
	localAdminSecretsDir        = "tmp"
	localAdminSecretsFile       = "tmp/local_admin_secrets.txt" // #nosec G101 -- file path only, not an embedded credential.
	localAdminPasswordKey       = "SAFE_ZONE_ADMIN_PASSWORD" // #nosec G101 -- environment variable name, not a credential value.
	localAdminAPIKeyKey         = "SAFE_ZONE_ADMIN_API_KEY"  // #nosec G101 -- environment variable name, not a credential value.
)

type runtimeSecurity struct {
	sessionSecret []byte
	// adminPasswordHash is the bcrypt hash computed once at startup. The
	// plaintext password is never kept in memory after load.
	adminPasswordHash string
	adminAPIKey       string
}

func loadRuntimeSecurity() (runtimeSecurity, error) {
	// The security profile must be explicit: an empty or unknown
	// SAFE_ZONE_ENV refuses to start instead of silently falling back to
	// lenient local behavior.
	env, err := config.NormalizeEnvironment(os.Getenv("SAFE_ZONE_ENV"))
	if err != nil {
		return runtimeSecurity{}, err
	}

	sessionSeed, err := auth.GenerateSecureRandomString(generatedSessionSecretBytes)
	if err != nil {
		return runtimeSecurity{}, fmt.Errorf("generate session secret: %w", err)
	}

	adminPassword, err := config.SecretStringE(localAdminPasswordKey)
	if err != nil {
		return runtimeSecurity{}, err
	}
	adminAPIKey, err := config.SecretStringE(localAdminAPIKeyKey)
	if err != nil {
		return runtimeSecurity{}, err
	}

	if config.EnvironmentRequiresValidatedSecrets(env) {
		if err := validateProductionAdminPassword(adminPassword); err != nil {
			return runtimeSecurity{}, err
		}
		if err := validateProductionAdminAPIKey(adminAPIKey); err != nil {
			return runtimeSecurity{}, err
		}
	} else {
		generatedAdminPassword := ""
		generatedAdminAPIKey := ""
		reusedAdminPassword := false
		reusedAdminAPIKey := false

		// Local/test profiles may run without configured credentials. Reuse
		// the ones generated by an earlier start, otherwise every restart
		// rotates the admin password and API key even when the secrets file
		// on disk survives (a named volume or a persistent workdir).
		storedSecrets := map[string]string{}
		if adminPassword == "" || adminAPIKey == "" {
			storedSecrets, err = readLocalAdminSecrets()
			if err != nil {
				return runtimeSecurity{}, err
			}
		}

		if adminPassword == "" && !secretFileConfigured(localAdminPasswordKey) {
			if stored := storedSecrets[localAdminPasswordKey]; stored != "" {
				adminPassword = stored
				reusedAdminPassword = true
				logjson.Info("reused previously generated local-only admin password", map[string]any{
					"service":      "core-api",
					"config_key":   localAdminPasswordKey,
					"secrets_file": localAdminSecretsFile,
				})
			}
		}
		if adminPassword == "" {
			adminPassword, err = auth.GenerateSecureRandomString(generatedAdminPasswordBytes)
			if err != nil {
				return runtimeSecurity{}, fmt.Errorf("generate admin password: %w", err)
			}
			generatedAdminPassword = adminPassword
			logjson.Warn("generated temporary local-only admin password", map[string]any{
				"service":        "core-api",
				"config_key":     localAdminPasswordKey,
				"generated_only": true,
			})
		} else if err := validateProductionAdminPassword(adminPassword); err != nil {
			logjson.Warn("admin password validation warning", map[string]any{
				"service": "core-api",
				"error":   err.Error(),
			})
		}

		if adminAPIKey == "" && !secretFileConfigured(localAdminAPIKeyKey) {
			if stored := storedSecrets[localAdminAPIKeyKey]; stored != "" {
				adminAPIKey = stored
				reusedAdminAPIKey = true
				logjson.Info("reused previously generated local-only admin api key", map[string]any{
					"service":      "core-api",
					"config_key":   localAdminAPIKeyKey,
					"secrets_file": localAdminSecretsFile,
				})
			}
		}
		if adminAPIKey == "" {
			adminAPIKey, err = auth.GenerateSecureRandomString(generatedAdminAPIKeyBytes)
			if err != nil {
				return runtimeSecurity{}, fmt.Errorf("generate admin api key: %w", err)
			}
			generatedAdminAPIKey = adminAPIKey
			logjson.Warn("generated temporary local-only admin api key", map[string]any{
				"service":        "core-api",
				"config_key":     localAdminAPIKeyKey,
				"generated_only": true,
			})
		} else if err := validateProductionAdminAPIKey(adminAPIKey); err != nil {
			logjson.Warn("admin api key validation warning", map[string]any{
				"service": "core-api",
				"error":   err.Error(),
			})
		}

		if generatedAdminPassword != "" || generatedAdminAPIKey != "" {
			fileSecrets := map[string]string{}
			if generatedAdminPassword != "" || reusedAdminPassword {
				fileSecrets[localAdminPasswordKey] = adminPassword
			}
			if generatedAdminAPIKey != "" || reusedAdminAPIKey {
				fileSecrets[localAdminAPIKeyKey] = adminAPIKey
			}
			if err := writeLocalAdminSecrets(fileSecrets); err != nil {
				return runtimeSecurity{}, err
			}
			logjson.Warn("temporary local-only admin secrets generated and saved to file", map[string]any{
				"service":      "core-api",
				"secrets_file": localAdminSecretsFile,
			})
		}
	}

	// bcrypt silently truncates (or rejects) inputs beyond 72 bytes, so the
	// byte limit is validated for every profile before hashing. len() counts
	// bytes, not runes, matching the bcrypt contract.
	if len(adminPassword) > maxAdminPasswordBytes {
		return runtimeSecurity{}, fmt.Errorf("SAFE_ZONE_ADMIN_PASSWORD must be at most %d bytes for bcrypt hashing (got %d bytes)", maxAdminPasswordBytes, len(adminPassword))
	}

	// Hash the admin password exactly once at startup. Login requests only
	// ever see the bcrypt hash, so a memory or config snapshot after load
	// yields no fast verifier for the secret.
	adminPasswordHash, err := auth.HashPassword(adminPassword)
	if err != nil {
		return runtimeSecurity{}, fmt.Errorf("hash admin password: %w", err)
	}

	logjson.Info("runtime security profile loaded", map[string]any{
		"service":       "core-api",
		"environment":   env,
		"password_hash": "bcrypt",
	})

	return runtimeSecurity{
		sessionSecret:     []byte(sessionSeed),
		adminPasswordHash: adminPasswordHash,
		adminAPIKey:       adminAPIKey,
	}, nil
}

// secretFileConfigured reports whether the operator pointed KEY_FILE at a
// secret file. An explicitly configured but empty file must not silently fall
// back to the generated local secret.
func secretFileConfigured(key string) bool {
	return strings.TrimSpace(os.Getenv(key+"_FILE")) != ""
}

// readLocalAdminSecrets loads credentials generated by an earlier local start.
// A missing file is not an error: nothing has been generated yet. Malformed or
// unknown lines are ignored so a hand-edited file does not block startup; only
// the two keys this service writes are ever returned.
func readLocalAdminSecrets() (map[string]string, error) {
	data, err := os.ReadFile(localAdminSecretsFile)
	if errors.Is(err, os.ErrNotExist) {
		return map[string]string{}, nil
	}
	if err != nil {
		return nil, fmt.Errorf("read local admin secrets file: %w", err)
	}

	secrets := map[string]string{}
	for _, line := range strings.Split(string(data), "\n") {
		key, value, ok := strings.Cut(strings.TrimSpace(line), "=")
		if !ok || value == "" {
			continue
		}
		switch key {
		case localAdminPasswordKey, localAdminAPIKeyKey:
			secrets[key] = value
		}
	}
	return secrets, nil
}

func writeLocalAdminSecrets(secrets map[string]string) error {
	var content strings.Builder
	for _, key := range []string{localAdminPasswordKey, localAdminAPIKeyKey} {
		if value := secrets[key]; value != "" {
			content.WriteString(key)
			content.WriteString("=")
			content.WriteString(value)
			content.WriteString("\n")
		}
	}

	if err := os.MkdirAll(localAdminSecretsDir, 0o750); err != nil {
		return fmt.Errorf("create local admin secrets directory: %w", err)
	}
	if err := os.WriteFile(localAdminSecretsFile, []byte(content.String()), 0o600); err != nil {
		return fmt.Errorf("write local admin secrets file: %w", err)
	}
	return nil
}

func validateProductionAdminPassword(password string) error {
	password = strings.TrimSpace(password)
	if password == "" {
		return fmt.Errorf("SAFE_ZONE_ADMIN_PASSWORD or SAFE_ZONE_ADMIN_PASSWORD_FILE is required when SAFE_ZONE_ENV=%s", config.Environment())
	}
	if len(password) < minAdminPasswordLength {
		return fmt.Errorf("SAFE_ZONE_ADMIN_PASSWORD is too weak: need at least %d characters", minAdminPasswordLength)
	}
	if looksPlaceholderSecret(password) {
		return fmt.Errorf("SAFE_ZONE_ADMIN_PASSWORD uses a placeholder-style value; replace it with a real secret")
	}
	return nil
}

func validateProductionAdminAPIKey(apiKey string) error {
	apiKey = strings.TrimSpace(apiKey)
	if apiKey == "" {
		return fmt.Errorf("SAFE_ZONE_ADMIN_API_KEY or SAFE_ZONE_ADMIN_API_KEY_FILE is required when SAFE_ZONE_ENV=%s", config.Environment())
	}
	if len(apiKey) < minAdminAPIKeyLength {
		return fmt.Errorf("SAFE_ZONE_ADMIN_API_KEY is too short: need at least %d characters", minAdminAPIKeyLength)
	}
	if looksPlaceholderSecret(apiKey) {
		return fmt.Errorf("SAFE_ZONE_ADMIN_API_KEY uses a placeholder-style value; replace it with a real secret")
	}
	return nil
}

func looksPlaceholderSecret(value string) bool {
	normalized := strings.ToLower(strings.TrimSpace(value))
	replacer := strings.NewReplacer("-", "", "_", "", " ", "")
	normalized = replacer.Replace(normalized)

	if normalized == "" {
		return true
	}

	exactPlaceholders := []string{
		"password",
		"adminpassword",
		"apikey",
		"token",
		"secret",
		"testkey",
		"testpass",
		"example",
		"sample",
		"placeholder",
	}

	for _, marker := range exactPlaceholders {
		if normalized == marker {
			return true
		}
	}

	patternPlaceholders := []string{
		"changeme",
		"replacewith",
		"your",
		// The dev-stack defaults this repository used to ship
		// (SafeRoadLocalAdmin123!, SafeRoadLocalApiKey1234567890) are
		// public in git history. Any value built on that prefix must
		// never pass the production gate, even though it clears the
		// length checks above.
		"saferoad",
	}

	for _, marker := range patternPlaceholders {
		if strings.HasPrefix(normalized, marker) || strings.Contains(normalized, marker) {
			return true
		}
	}

	return false
}
